//! Mascot `.dat` import from a hand-written file; expected values derived
//! by hand below. Real files run only when `TUFFOLD_MASCOT_SAMPLES` names a
//! folder of `.dat` files.

use std::path::{Path, PathBuf};

use tuffold_core::SpectrumKey;
use tuffold_io::{MascotError, import_mascot};

// Masses by hand (monoisotopic residues + water 18.010565):
// MPEPTIDE = 930.400435 (see the MaxQuant test) + oxidation 15.994915
//   = 946.395350.
// ACDCK = 538.187955 + 2 × carbamidomethyl 57.021464 (fixed) = 652.230883.
// EDITPEPK (decoy) = 927.454905.
// Expectation value of q1_p1: 200 candidates × 10^(−55.2/10) = 6.0398e−4.
fn dat(peptide_mass: &str) -> String {
    let b = "--gc0p4Jq0M2Yt08jU534c0p";
    let section = |name: &str, body: &str| {
        format!("{b}\nContent-Type: application/x-Mascot; name=\"{name}\"\n\n{body}\n")
    };
    [
        "MIME-Version: 1.0 (Generated by Mascot version 1.0)\n\
         Content-Type: multipart/mixed; boundary=gc0p4Jq0M2Yt08jU534c0p\n\n"
            .to_string(),
        section(
            "parameters",
            "FILE=C:\\data\\run1.mgf\nMASS=Monoisotopic\nDECOY=1",
        ),
        section(
            "masses",
            "C=103.009185\ndelta1=15.994915,Oxidation (M)\n\
             FixedMod1=57.021464,Carbamidomethyl (C)\nFixedModResidues1=C",
        ),
        section("header", "version=2.4.1\nqueries=2"),
        section(
            "summary",
            "qexp1=474.205,2+\nqmatch1=200\nqplughole1=20.5\nqexp2=464.73,2+\nqmatch2=150",
        ),
        section("decoy_summary", "qmatch1=200\nqplughole1=19"),
        section(
            "peptides",
            &format!(
                "q1_p1=0,{peptide_mass},0.001,5,MPEPTIDE,10,0100000000,55.2,0000000000,0,0;\
                 \"P1\":0:1:8:1,\"P2\":0:5:12:1\n\
                 q1_p1_terms=-,K:R,A\n\
                 q1_p2=0,652.230883,0.1,3,ACDCK,8,0000000,20.1,0000,0,0;\"P3\":0:1:5:1\n\
                 q2_p1=-1"
            ),
        ),
        section(
            "decoy_peptides",
            "q1_p1=0,927.454905,0.0,2,EDITPEPK,4,0000000000,12.3,000,0,0;\"P1\":0:3:10:1",
        ),
        section("proteins", "\"P1\"=12345.6,\"Protein one\""),
        section(
            "query1",
            "title=run1%2E100%2E100%2E2\nrtinseconds=600.5\nscans=100",
        ),
        section("query2", "title=no%20scan"),
        format!("{b}--\n"),
    ]
    .concat()
}

fn write(dir: &Path, text: &str) -> PathBuf {
    let path = dir.join("F001.dat");
    std::fs::write(&path, text).unwrap();
    path
}

#[test]
fn matches_modifications_scores_and_decoys_import() {
    let dir = tempfile::tempdir().unwrap();
    let imported = import_mascot(&write(dir.path(), &dat("946.395350"))).unwrap();
    let batch = &imported.batch;
    assert_eq!(batch.software.version.as_deref(), Some("2.4.1"));
    assert_eq!(batch.ms_runs[0].name, "run1");
    assert_eq!(batch.spectra.len(), 1);
    assert_eq!(batch.spectra[0].key, SpectrumKey::Scan(100));
    assert_eq!(batch.spectra[0].rt_seconds, Some(600.5));
    assert_eq!(batch.psms.len(), 3);

    let best = &batch.psms[0];
    assert_eq!(
        (best.rank, best.peptide.proforma().as_str()),
        (1, "M[+15.9949]PEPTIDE")
    );
    assert_eq!(best.evidence.len(), 2);
    assert_eq!(
        (best.evidence[0].pre, best.evidence[0].post),
        (Some('-'), Some('K'))
    );
    assert_eq!(
        (best.evidence[1].pre, best.evidence[1].post),
        (Some('R'), Some('A'))
    );
    let expect = best
        .scores
        .iter()
        .find(|s| s.name == "Mascot:expectation value")
        .unwrap();
    assert!((expect.value - 6.0398e-4).abs() < 1e-7, "{}", expect.value);

    let second = &batch.psms[1];
    assert_eq!(
        (second.rank, second.peptide.proforma().as_str()),
        (2, "AC[+57.0215]DC[+57.0215]K")
    );

    let decoy = &batch.psms[2];
    assert_eq!(decoy.evidence[0].accession, "DECOY_P1");
    assert!(batch.decoy_index().is_decoy(decoy) && !batch.decoy_index().is_decoy(best));
    let p1 = batch.proteins.iter().find(|p| p.accession == "P1").unwrap();
    assert_eq!(p1.description.as_deref(), Some("Protein one"));
}

#[test]
fn wrong_masses_refuse_the_file() {
    let dir = tempfile::tempdir().unwrap();
    // 1 of 3 matches off by 16 Da (> 5%).
    let error = import_mascot(&write(dir.path(), &dat("930.400435"))).unwrap_err();
    assert!(
        matches!(
            error,
            MascotError::Masses {
                failures: 1,
                checked: 3,
                ..
            }
        ),
        "{error}"
    );
}

#[test]
fn other_dat_files_are_not_mascot() {
    let dir = tempfile::tempdir().unwrap();
    let error = import_mascot(&write(dir.path(), "just some numbers\n1 2 3\n")).unwrap_err();
    assert!(matches!(error, MascotError::NotMascot { .. }), "{error}");
}

#[test]
#[ignore = "needs Mascot .dat files (TUFFOLD_MASCOT_SAMPLES)"]
fn sample_files_import() {
    let folder = std::env::var("TUFFOLD_MASCOT_SAMPLES").expect("set TUFFOLD_MASCOT_SAMPLES");
    for entry in std::fs::read_dir(folder).unwrap().flatten() {
        let path = entry.path();
        if !path
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("dat"))
        {
            continue;
        }
        let imported = import_mascot(&path).unwrap_or_else(|e| panic!("{e}"));
        let batch = &imported.batch;
        let decoys = batch.decoy_index();
        let rank_one = batch.psms.iter().filter(|psm| psm.rank == 1).count();
        let decoy = batch
            .psms
            .iter()
            .filter(|psm| psm.rank == 1 && decoys.is_decoy(psm))
            .count();
        println!(
            "== {}: {} spectra, {} PSMs ({rank_one} rank 1, {decoy} decoy), {} proteins",
            path.display(),
            batch.spectra.len(),
            batch.psms.len(),
            batch.proteins.len()
        );
        for note in &imported.notes {
            println!("   note: {note}");
        }
    }
}
