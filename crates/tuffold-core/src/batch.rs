//! The unit every importer produces and the store consumes.
//!
//! An [`ImportBatch`] is self-contained: records refer to one another by
//! natural keys (MS-run name, spectrum key, ProForma key, accession), never by
//! database ids. The store deduplicates on those keys, so importing a second
//! search of the same runs attaches its PSMs to the same spectra, peptides, and
//! proteins — which is what multi-engine comparison needs.

use std::collections::HashMap;

use serde::{Deserialize, Serialize};

use crate::peptide::PeptideForm;

/// Input file formats Tuffold can import.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SourceFormat {
    FragPipeBundle,
    PepXml,
    MzIdentMl,
    /// Generated by Tuffold (the demo project), not read from a file.
    Synthetic,
    /// Searched by Tuffold's built-in search (Sage); the path is the
    /// spectra file searched.
    SageSearch,
    /// A Scaffold project (`.sf3`), read but never written.
    Sf3,
    /// A Scaffold `.sfdb` file (Scaffold 5, Scaffold DDA), read but never
    /// written.
    Sfdb,
    /// Proteome Discoverer results (`.pdResult`, `.msf`).
    ProteomeDiscoverer,
    /// A MaxQuant `txt` folder (or its `msms.txt`).
    MaxQuant,
    /// A Mascot results file (`.dat`).
    Mascot,
}

impl SourceFormat {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::FragPipeBundle => "fragpipe_bundle",
            Self::PepXml => "pepxml",
            Self::MzIdentMl => "mzidentml",
            Self::Synthetic => "synthetic",
            Self::SageSearch => "sage_search",
            Self::Sf3 => "sf3",
            Self::Sfdb => "sfdb",
            Self::ProteomeDiscoverer => "proteome_discoverer",
            Self::MaxQuant => "maxquant",
            Self::Mascot => "mascot",
        }
    }
}

/// The search engine (or pipeline) that produced the identifications.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct Software {
    pub name: String,
    pub version: Option<String>,
}

/// A biological sample; MS runs (fractions, replicates) belong to one.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BioSample {
    pub name: String,
    /// Grouping for comparisons (e.g. "control"); `None` until assigned.
    pub category: Option<String>,
}

/// One acquisition (raw file).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MsRun {
    /// Run name, normally the raw file's base name without extension.
    pub name: String,
    pub biosample: String,
    /// The spectra file the source names, verbatim.
    pub spectra_file: Option<String>,
}

/// How a spectrum is identified inside its run. Ordered from most to least
/// reliable for matching the same spectrum across search engines.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case", tag = "kind", content = "value")]
pub enum SpectrumKey {
    Scan(u32),
    Index(u32),
    /// Free-form native id or title when neither scan nor index is known.
    Native(String),
}

impl SpectrumKey {
    /// Derive a key from an mzML-style native id (`... scan=1234`, `index=5`)
    /// or fall back to the verbatim id.
    ///
    /// Waters ids (`function=2 process=0 scan=5`) repeat scan numbers across
    /// functions, so they keep the whole id rather than collapsing to a scan.
    pub fn from_native_id(native_id: &str) -> Self {
        if native_id
            .split_whitespace()
            .any(|part| part.starts_with("function="))
        {
            return Self::Native(native_id.to_string());
        }
        let field = |name: &str| {
            native_id.split_whitespace().find_map(|part| {
                part.strip_prefix(name)
                    .and_then(|value| value.strip_prefix('='))
                    .and_then(|value| value.parse::<u32>().ok())
            })
        };
        if let Some(scan) = field("scan") {
            Self::Scan(scan)
        } else if let Some(index) = field("index") {
            Self::Index(index)
        } else {
            Self::Native(native_id.to_string())
        }
    }

    /// Stable text form used as the store's uniqueness key.
    pub fn canonical(&self) -> String {
        match self {
            Self::Scan(scan) => format!("scan={scan}"),
            Self::Index(index) => format!("index={index}"),
            Self::Native(native) => native.clone(),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Spectrum {
    pub ms_run: String,
    pub key: SpectrumKey,
    /// The source's own spectrum reference, verbatim (title, native id, ...).
    pub source_id: Option<String>,
    pub precursor_mz: Option<f64>,
    pub precursor_charge: Option<i16>,
    pub rt_seconds: Option<f64>,
}

impl Spectrum {
    /// Merge another record of the same spectrum (same run and key): unknown
    /// values are filled from it; a conflicting precursor charge (e.g. pepXML
    /// queries for the same scan at charge 2 and 3) becomes unknown rather
    /// than either guess.
    pub fn merge(&mut self, other: &Spectrum) {
        self.source_id = self.source_id.take().or_else(|| other.source_id.clone());
        self.precursor_mz = self.precursor_mz.or(other.precursor_mz);
        self.rt_seconds = self.rt_seconds.or(other.rt_seconds);
        self.precursor_charge = match (self.precursor_charge, other.precursor_charge) {
            (Some(mine), Some(theirs)) if mine != theirs => None,
            (mine, theirs) => mine.or(theirs),
        };
    }
}

/// A measured MS/MS spectrum from a spectra file (mzML, MGF), to attach to
/// the identified spectrum with the same run and key.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PeakSpectrum {
    pub key: SpectrumKey,
    /// The spectra file's own id (mzML native id or MGF title).
    pub native_id: String,
    pub ms_level: u8,
    pub rt_seconds: Option<f64>,
    pub precursor_mz: Option<f64>,
    pub precursor_charge: Option<i16>,
    pub mz: Vec<f64>,
    pub intensity: Vec<f32>,
    /// Profile (continuous) data rather than centroided peaks. Shown as
    /// is, but not searched: the search needs centroids.
    #[serde(default)]
    pub profile: bool,
    /// The native id of the scan this one was acquired from (mzML's
    /// `spectrumRef`), when the file says: an SPS-MS3 scan names the MS/MS
    /// scan whose fragments it isolated.
    #[serde(default)]
    pub parent: Option<String>,
    /// The m/z window isolated for fragmentation (absolute bounds), when the
    /// file says; precursor purity is measured in it.
    #[serde(default)]
    pub isolation: Option<(f64, f64)>,
    /// The precursor's ion mobility (1/K0, V·s/cm²), when the file has one
    /// (timsTOF).
    #[serde(default)]
    pub precursor_mobility: Option<f64>,
    /// Each peak's ion mobility (1/K0), for an MS1 frame binned by mobility
    /// (timsTOF); empty otherwise.
    #[serde(default)]
    pub mobility: Vec<f32>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Protein {
    pub accession: String,
    pub description: Option<String>,
    /// Upper-case sequence, when a database or the source supplied it.
    pub sequence: Option<String>,
    pub is_decoy: bool,
    /// The source flagged decoy status explicitly (mzIdentML `isDecoy`), as
    /// opposed to Tuffold inferring it from the accession convention.
    /// Explicit flags win over inferred ones when imports disagree.
    #[serde(default)]
    pub decoy_explicit: bool,
}

/// Where a PSM's peptide sits on one protein.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Evidence {
    pub accession: String,
    /// 1-based inclusive positions, when the source gave them.
    pub start: Option<u32>,
    pub end: Option<u32>,
    pub pre: Option<char>,
    pub post: Option<char>,
}

/// A named score as the source reported it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Score {
    pub name: String,
    /// PSI-MS accession (e.g. `MS:1002052`) when the source gave one.
    pub accession: Option<String>,
    pub value: f64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Psm {
    pub ms_run: String,
    pub spectrum: SpectrumKey,
    /// 1 = best hit for the spectrum.
    pub rank: u32,
    pub peptide: PeptideForm,
    pub charge: i16,
    pub calculated_mz: Option<f64>,
    pub experimental_mz: Option<f64>,
    /// The source's own threshold verdict (mzIdentML `passThreshold`).
    pub pass_threshold: Option<bool>,
    pub scores: Vec<Score>,
    pub evidence: Vec<Evidence>,
}

/// Everything one import produces.
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub struct ImportBatch {
    pub software: Software,
    pub biosamples: Vec<BioSample>,
    pub ms_runs: Vec<MsRun>,
    pub spectra: Vec<Spectrum>,
    pub proteins: Vec<Protein>,
    pub psms: Vec<Psm>,
}

impl ImportBatch {
    /// Decoy status lookups for the whole batch, built once.
    pub fn decoy_index(&self) -> DecoyIndex<'_> {
        DecoyIndex {
            proteins: self
                .proteins
                .iter()
                .map(|protein| (protein.accession.as_str(), protein.is_decoy))
                .collect(),
        }
    }

    /// Convenience for one PSM; use [`ImportBatch::decoy_index`] in loops.
    pub fn psm_is_decoy(&self, psm: &Psm) -> bool {
        self.decoy_index().is_decoy(psm)
    }
}

/// Decoy status by accession for one batch.
pub struct DecoyIndex<'a> {
    proteins: HashMap<&'a str, bool>,
}

impl DecoyIndex<'_> {
    /// A PSM is a decoy only when every protein it maps to is a decoy; a hit
    /// shared with any target protein counts as a target. Proteins the batch
    /// does not list follow the accession convention, as the store does.
    pub fn is_decoy(&self, psm: &Psm) -> bool {
        !psm.evidence.is_empty()
            && psm.evidence.iter().all(|evidence| {
                self.proteins
                    .get(evidence.accession.as_str())
                    .copied()
                    .unwrap_or_else(|| crate::decoy::is_decoy_accession(&evidence.accession))
            })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spectrum_keys_parse_native_ids() {
        let thermo = "controllerType=0 controllerNumber=1 scan=1234";
        assert_eq!(SpectrumKey::from_native_id(thermo), SpectrumKey::Scan(1234));
        assert_eq!(
            SpectrumKey::from_native_id("index=5"),
            SpectrumKey::Index(5)
        );
        assert_eq!(
            SpectrumKey::from_native_id("Cmpd 24, +MSn(1085.6886)"),
            SpectrumKey::Native("Cmpd 24, +MSn(1085.6886)".into())
        );
        assert_eq!(SpectrumKey::Scan(7).canonical(), "scan=7");
    }

    fn protein(accession: &str, is_decoy: bool) -> Protein {
        Protein {
            accession: accession.into(),
            description: None,
            sequence: None,
            is_decoy,
            decoy_explicit: false,
        }
    }

    fn psm(accessions: &[&str]) -> Psm {
        Psm {
            ms_run: "r".into(),
            spectrum: SpectrumKey::Scan(1),
            rank: 1,
            peptide: PeptideForm::unmodified("PEPTIDE"),
            charge: 2,
            calculated_mz: None,
            experimental_mz: None,
            pass_threshold: None,
            scores: vec![],
            evidence: accessions
                .iter()
                .map(|accession| Evidence {
                    accession: (*accession).into(),
                    start: None,
                    end: None,
                    pre: None,
                    post: None,
                })
                .collect(),
        }
    }

    #[test]
    fn psm_is_decoy_only_when_every_protein_is_a_decoy() {
        let batch = ImportBatch {
            proteins: vec![
                protein("T1", false),
                protein("rev_T1", true),
                protein("rev_T2", true),
            ],
            ..ImportBatch::default()
        };
        assert!(batch.psm_is_decoy(&psm(&["rev_T1", "rev_T2"])));
        assert!(!batch.psm_is_decoy(&psm(&["rev_T1", "T1"])));
        assert!(!batch.psm_is_decoy(&psm(&[])));
        // Unlisted proteins follow the accession convention.
        assert!(batch.psm_is_decoy(&psm(&["rev_T1", "DECOY_unlisted"])));
        assert!(!batch.psm_is_decoy(&psm(&["rev_T1", "unlisted"])));
    }

    #[test]
    fn waters_native_ids_keep_their_function() {
        let one = SpectrumKey::from_native_id("function=1 process=0 scan=5");
        let two = SpectrumKey::from_native_id("function=2 process=0 scan=5");
        assert_ne!(one, two);
        assert_eq!(
            one,
            SpectrumKey::Native("function=1 process=0 scan=5".into())
        );
    }

    fn spectrum(mz: Option<f64>, charge: Option<i16>, rt: Option<f64>) -> Spectrum {
        Spectrum {
            ms_run: "r".into(),
            key: SpectrumKey::Scan(1),
            source_id: None,
            precursor_mz: mz,
            precursor_charge: charge,
            rt_seconds: rt,
        }
    }

    #[test]
    fn merging_fills_unknowns_and_unsets_conflicting_charge() {
        let mut first = spectrum(None, Some(2), None);
        first.merge(&spectrum(Some(500.25), Some(2), Some(61.0)));
        assert_eq!(first, spectrum(Some(500.25), Some(2), Some(61.0)));

        first.merge(&spectrum(Some(999.0), Some(3), Some(1.0)));
        assert_eq!(first, spectrum(Some(500.25), None, Some(61.0)));
    }
}
